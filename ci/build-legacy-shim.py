"""Build the legacy ``pyramids-gis`` alias distribution.

After the rename ``pyramids-gis`` -> ``pyramids-core`` (see the rename tracking
issue), ``pyramids-gis`` lives on as a **thin alias**: it ships no code, it only
depends on the matching ``pyramids-core`` release, so ``pip install pyramids-gis``
keeps working and resolves to ``pyramids-core`` (``import pyramids`` unchanged).

This script is the single source of truth for that shim. It reads the current
version straight from the core ``pyproject.toml`` (``[project].version``), so the
shim can never drift out of lockstep, generates a minimal shim project in a temp
directory, and builds an sdist + wheel into ``--outdir`` (default ``dist-shim``).
CI then uploads the result to the ``pyramids-gis`` PyPI project alongside the real
``pyramids-core`` artifacts.

Usage::

    python ci/build-legacy-shim.py [--outdir dist-shim] [--version X.Y.Z]

``--version`` overrides the version read from ``pyproject.toml`` (used only for
testing the generator); normal runs take no arguments.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent
_CORE_PYPROJECT = _REPO_ROOT / "pyproject.toml"

_SHIM_PYPROJECT = """\
# GENERATED by ci/build-legacy-shim.py — do not edit by hand.
# Thin alias of pyramids-core; ships no code, only the pinned dependency.
[build-system]
requires = ["setuptools>=77"]
build-backend = "setuptools.build_meta"

[project]
name = "pyramids-gis"
version = "{version}"
description = "Deprecated alias of pyramids-core. Install pyramids-core instead."
readme = {{ text = "{readme}", content-type = "text/markdown" }}
license = {{ text = "GNU General Public License v3" }}
authors = [{{ name = "Mostafa Farrag", email = "moah.farag@gmail.com" }}]
requires-python = ">= 3.11, <4"
dependencies = ["pyramids-core=={version}"]

[project.urls]
homepage = "https://github.com/serapeum-org/pyramids-core"

[tool.setuptools]
# No packages: pyramids-core owns the importable `pyramids` package. The shim is
# metadata only, so installing both distributions never fights over files.
py-modules = []
"""

_SHIM_README = (
    "# pyramids-gis (deprecated alias)\\n\\n"
    "`pyramids-gis` has been renamed to **`pyramids-core`**. This distribution is "
    "now a thin alias that just depends on `pyramids-core`; install `pyramids-core` "
    "directly. The import name stays `pyramids`."
)


def _read_core_version() -> str:
    """Return ``[project].version`` from the core ``pyproject.toml``."""
    with _CORE_PYPROJECT.open("rb") as handle:
        data = tomllib.load(handle)
    return data["project"]["version"]


def _build_shim(version: str, outdir: Path) -> int:
    """Generate the shim project for ``version`` and build sdist + wheel into ``outdir``."""
    outdir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        project = Path(tmp)
        (project / "pyproject.toml").write_text(
            _SHIM_PYPROJECT.format(version=version, readme=_SHIM_README),
            encoding="utf-8",
        )
        result = subprocess.run(
            [sys.executable, "-m", "build", "--outdir", str(outdir), str(project)],
            check=False,
        )
    return result.returncode


def main(argv: list[str] | None = None) -> int:
    """Parse arguments, build the shim, and return the build's exit code."""
    parser = argparse.ArgumentParser(description="Build the pyramids-gis alias shim.")
    parser.add_argument(
        "--outdir", default="dist-shim", help="output directory for the built artifacts"
    )
    parser.add_argument(
        "--version", default=None, help="override the version (testing only)"
    )
    args = parser.parse_args(argv)
    version = args.version or _read_core_version()
    outdir = Path(args.outdir)
    code = _build_shim(version, outdir)
    if code == 0:
        print(
            f"built pyramids-gis=={version} shim (-> pyramids-core=={version}) into {outdir}"
        )
    return code


if __name__ == "__main__":
    raise SystemExit(main())
